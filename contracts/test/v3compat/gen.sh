#!/bin/sh
# Re-targets the whole PayRunV2 test suite at PayRunV3 (same names, same behaviour expected), so V3 is proven to keep every
# V2 rule. Regenerate after changing a V2 test: sh test/v3compat/gen.sh (make contracts-test checks the copies are current).
set -eu
cd "$(dirname "$0")/.."
for f in PayRunV2.t.sol PayRunV2Hold.t.sol PayRunV2Fuzz.t.sol; do
  out="v3compat/$(echo "$f" | sed 's/PayRunV2/PayRunV3Compat/')"
  { echo "// GENERATED by test/v3compat/gen.sh from test/$f: do not edit."
    sed -e 's/PayRunV2/PayRunV3/g' -e 's#"\./PayRun\.t\.sol"#"../PayRun.t.sol"#' -e 's#"\.\./src/#"../../src/#' \
        -e 's/contract PayRunV3\([A-Za-z]*\)Test is/contract PayRunV3Compat\1Test is/' "$f"; } > "$out.tmp"
  mv "$out.tmp" "$out"
done
